"""
Feature 4 — human review log + HTML report tests.

Covers scripts/review.py (append-only, hash-chained review log) and
scripts/report_html.py (standalone escaped HTML rendering).

The sample automated report is generated by running the real pipeline
(compliance_agent.run, use_llm=False) on the seeded synthetic report
synthetic_reports/02_privacy_violation.txt, which deterministically
produces a FAIL with a `privacy` violation. All fixtures are synthetic.
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
REVIEW_PY = REPO_ROOT / "scripts" / "review.py"
REPORT_HTML_PY = REPO_ROOT / "scripts" / "report_html.py"
GENESIS = "0" * 64

sys.path.insert(0, str(REPO_ROOT))


def run_cli(script: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(script), *args],
        capture_output=True,
        text=True,
    )


@pytest.fixture(scope="module")
def sample_report(tmp_path_factory) -> Path:
    """Real automated report (rules-only) for the privacy synthetic report."""
    import compliance_agent

    text = (REPO_ROOT / "synthetic_reports" / "02_privacy_violation.txt").read_text(
        encoding="utf-8"
    )
    report = compliance_agent.run(text, use_llm=False)
    assert report["compliance_status"] == "FAIL"
    assert any(v["rule_id"] == "privacy" for v in report["violations"])
    path = tmp_path_factory.mktemp("f4") / "report.json"
    path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    return path


def add_decision(report: Path, log: Path, **overrides) -> subprocess.CompletedProcess:
    args = {
        "--report": str(report),
        "--rule-id": "privacy",
        "--decision": "confirmed",
        "--rationale": "Verified against source document.",
        "--reviewer": "Jane Doe",
        "--log": str(log),
    }
    args.update(overrides)
    flat = [item for pair in args.items() for item in pair]
    return run_cli(REVIEW_PY, "add", *flat)


def read_log(log: Path) -> list[dict]:
    return [json.loads(line) for line in log.read_text(encoding="utf-8").splitlines() if line.strip()]


# ---------------------------------------------------------------- add/verify

def test_add_then_verify_ok(sample_report, tmp_path):
    log = tmp_path / "reviews.jsonl"
    res = add_decision(sample_report, log)
    assert res.returncode == 0, res.stderr

    res = run_cli(REVIEW_PY, "verify", "--log", str(log))
    assert res.returncode == 0
    assert "OK" in res.stdout and "1 record" in res.stdout


def test_two_adds_chain_correctly(sample_report, tmp_path):
    log = tmp_path / "reviews.jsonl"
    assert add_decision(sample_report, log).returncode == 0
    assert add_decision(
        sample_report, log, **{"--decision": "escalated", "--rationale": "Needs senior review."}
    ).returncode == 0

    first, second = read_log(log)
    assert first["prev_hash"] == GENESIS
    assert second["prev_hash"] == first["record_hash"]

    res = run_cli(REVIEW_PY, "verify", "--log", str(log))
    assert res.returncode == 0


def test_tampered_record_detected_at_exact_index(sample_report, tmp_path):
    log = tmp_path / "reviews.jsonl"
    assert add_decision(sample_report, log).returncode == 0
    assert add_decision(
        sample_report, log, **{"--rationale": "Second decision, also genuine."}
    ).returncode == 0

    # Tamper with the SECOND record's stored rationale (index 1).
    records = read_log(log)
    records[1]["rationale"] = "Forged rationale written after the fact."
    log.write_text(
        "".join(json.dumps(r) + "\n" for r in records), encoding="utf-8"
    )

    res = run_cli(REVIEW_PY, "verify", "--log", str(log))
    assert res.returncode != 0
    assert "record index 1" in (res.stdout + res.stderr)


def test_export_shape(sample_report, tmp_path):
    log = tmp_path / "reviews.jsonl"
    assert add_decision(sample_report, log).returncode == 0

    res = run_cli(REVIEW_PY, "export", "--log", str(log), "--format", "json")
    assert res.returncode == 0
    dump = json.loads(res.stdout)
    assert dump["record_count"] == 1
    assert dump["chain_valid"] is True
    assert dump["chain_break"] is None
    (record,) = dump["records"]
    for field in (
        "timestamp", "report_sha256", "rule_id", "evidence_excerpt",
        "decision", "rationale", "reviewer", "prev_hash", "record_hash",
    ):
        assert field in record
    assert record["decision"] == "confirmed"
    assert record["rule_id"] == "privacy"
    assert record["evidence_excerpt"]  # copied from the report's violation


