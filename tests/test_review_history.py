def test_html_report_escapes_untrusted_text(tmp_path):
    malicious = "<script>alert(1)</script>"
    report = {
        "compliance_status": "FAIL",
        "violations": [
            {
                "type": "Patient Privacy Violation",
                "severity": "critical",
                "evidence": malicious,
                "rule_id": "privacy",
                "regulatory_basis": "",
                "explanation": "see <b>this</b>",
                "suggested_fix": "",
            }
        ],
        "retrieved_regulations": [{"source": "Synthetic Source", "text": "Clause <i>x</i>"}],
    }
    report_path = tmp_path / "crafted_report.json"
    report_path.write_text(json.dumps(report), encoding="utf-8")

    log = tmp_path / "reviews.jsonl"
    res = add_decision(
        report_path, log,
        **{
            "--rationale": "Confirmed <img src=x onerror=alert(2)> in source.",
            "--reviewer": "Eve <script>alert(3)</script>",
        },
    )
    assert res.returncode == 0, res.stderr

    out = tmp_path / "report.html"
    res = run_cli(
        REPORT_HTML_PY,
        "--report", str(report_path),
        "--log", str(log),
        "--out", str(out),
    )
    assert res.returncode == 0, res.stderr
    html_out = out.read_text(encoding="utf-8")

    # Standing disclaimer banner is present.
    assert "Automated preliminary flags for qualified human review" in html_out
    assert "not a legal compliance determination" in html_out

    # Malicious strings appear ONLY in escaped form.
    assert malicious not in html_out
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in html_out
    assert "<img src=x" not in html_out
    assert "&lt;img src=x" in html_out
    assert "<script>alert(3)</script>" not in html_out

    # The joined review decision is rendered (reviewer + decision + rationale).
    assert "Eve" in html_out
    assert "confirmed" in html_out

    # Standalone: no external assets.
    assert "http://" not in html_out and "https://" not in html_out


def test_html_report_without_log(tmp_path):
    report = {"compliance_status": "PASS", "violations": [], "retrieved_regulations": []}
    report_path = tmp_path / "clean_report.json"
    report_path.write_text(json.dumps(report), encoding="utf-8")
    out = tmp_path / "clean.html"
    res = run_cli(REPORT_HTML_PY, "--report", str(report_path), "--out", str(out))
    assert res.returncode == 0, res.stderr
    html_out = out.read_text(encoding="utf-8")
    assert "PASS" in html_out
    assert "No human review decisions recorded" in html_out
